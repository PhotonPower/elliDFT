#!/usr/bin/env python3
"""Generate src/grid/lebedev_tables.inc from third_party/lebedev/Lebedev-Laikov.F.

Each subroutine LDnnnn of the Fortran file builds one grid by calling
GEN_OH(code, ..., A, B, V) once per orbit of the octahedral group, with the
parameters A, B and the weight V assigned just before. This script extracts
the sequence (code, A, B, V) of every grid; the orbits are expanded into
points in src/grid/lebedev.cpp. Numbers are copied digit for digit.

Usage: python3 scripts/generate_lebedev_tables.py
"""

import hashlib
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = ROOT / "third_party" / "lebedev" / "Lebedev-Laikov.F"
TARGET = ROOT / "src" / "grid" / "lebedev_tables.inc"
POINTS_PER_CODE = {1: 6, 2: 12, 3: 8, 4: 24, 5: 24, 6: 48}

NUMBER = r"([-+]?\d*\.\d+D[-+]?\d+)"


def c_double(fortran: str) -> str:
    return fortran.replace("D", "e")


def main() -> None:
    if not SOURCE.exists():
        raise SystemExit(
            f"{SOURCE} not found. The file is not part of the repository; "
            "download it from the source given in third_party/lebedev/README.md "
            "and check its SHA-256 there.")
    text = SOURCE.read_text()
    grids = []  # (n_points, [(code, a, b, v)])
    current = None
    a = b = v = "0.0D+0"
    for line in text.splitlines():
        if line[:1] in ("c", "C", "*"):  # comment line
            continue
        m = re.match(r"\s+SUBROUTINE LD(\d{4})\(", line)
        if m:
            current = (int(m.group(1)), [])
            grids.append(current)
            a = b = v = "0.0D+0"
            continue
        if current is None:
            continue
        m = re.match(r"\s+([ABV])=" + NUMBER + r"\s*$", line)
        if m:
            if m.group(1) == "A":
                a = m.group(2)
            elif m.group(1) == "B":
                b = m.group(2)
            else:
                v = m.group(2)
            continue
        m = re.match(r"\s+Call GEN_OH\(\s*(\d),", line)
        if m:
            code = int(m.group(1))
            # A and B are inputs of GEN_OH only for the codes that use them.
            current[1].append((code, a if code >= 4 else "0.0D+0", b if code == 6 else "0.0D+0", v))

    assert len(grids) == 32, len(grids)
    lines = [
        "// Generated by scripts/generate_lebedev_tables.py from",
        "// third_party/lebedev/Lebedev-Laikov.F (SHA-256 " + hashlib.sha256(text.encode()).hexdigest() + ").",
        "// Do not edit. One line per orbit of the octahedral group: {code, a, b, weight}.",
        "// V.I. Lebedev, D.N. Laikov, Doklady Mathematics 59, 477 (1999), as cited in that file.",
        "",
    ]
    index = ["static const LebedevTable lebedev_tables[] = {"]
    for n_points, orbits in grids:
        total = sum(POINTS_PER_CODE[code] for code, *_ in orbits)
        assert total == n_points, (n_points, total)
        weight_sum = sum(POINTS_PER_CODE[code] * float(c_double(v)) for code, _, _, v in orbits)
        assert abs(weight_sum - 1.0) < 1e-13, (n_points, weight_sum)
        lines.append(f"static const LebedevOrbit lebedev_orbits_{n_points:04d}[] = {{")
        for code, a, b, v in orbits:
            lines.append(f"  {{{code}, {c_double(a)}, {c_double(b)}, {c_double(v)}}},")
        lines.append("};")
        index.append(f"  {{{n_points}, {len(orbits)}, lebedev_orbits_{n_points:04d}}},")
    index.append("};")
    TARGET.write_text("\n".join(lines + [""] + index) + "\n")
    print(f"wrote {TARGET.relative_to(ROOT)}: {len(grids)} grids, "
          f"{sum(len(o) for _, o in grids)} orbits")


if __name__ == "__main__":
    main()
